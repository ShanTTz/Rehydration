def analyze(input_path: Path, output_dir: Path) -> dict[str, object]:
    ratings = _add_validity_columns(pd.read_csv(input_path))
    required = {"item_id", "assignment_id"}
    missing = required.difference(ratings.columns)
    if missing:
        raise ValueError(f"missing required columns: {sorted(missing)}")

    summary: dict[str, object] = {
        "ratings": int(len(ratings)),
        "items": int(ratings["item_id"].nunique()),
        "anonymous_assignments": int(ratings["assignment_id"].nunique()),
        "interval_method": "OLS intercept with two-way item and assignment cluster-robust covariance",
    }

    summary["acceptable"] = {
        source: _clustered_mean(
            ratings[f"{source}_acceptable"], ratings["item_id"], ratings["assignment_id"]
        )
        for source in ("frame", "verbatim")
    }
    summary["strict"] = {
        source: _clustered_mean(
            ratings[f"{source}_strict"], ratings["item_id"], ratings["assignment_id"]
        )
        for source in ("frame", "verbatim")
    }

    differences = {
        "acceptable": ratings["frame_acceptable"] - ratings["verbatim_acceptable"],
        "strict": ratings["frame_strict"] - ratings["verbatim_strict"],
        "relevance": ratings["frame_relevance"] - ratings["verbatim_relevance"],
        "coherence": ratings["frame_coherence"] - ratings["verbatim_coherence"],
        "mismatch": ratings["frame_mismatch"] - ratings["verbatim_mismatch"],
    }
    summary["paired_differences"] = {
        name: _clustered_mean(values, ratings["item_id"], ratings["assignment_id"])
        for name, values in differences.items()
    }

    frame_acceptable = ratings["frame_acceptable"]
    balance: dict[str, dict[str, float]] = {}
    for name, indicator in (
        ("conflict_minus_baseline", ratings["core"].eq("toxic")),
        ("controversial_minus_best", ratings["ranking"].eq("controversial")),
    ):
        balance[name] = _clustered_slope(
            frame_acceptable,
            indicator,
            ratings["item_id"],
            ratings["assignment_id"],
        )
    for name, level in (("deep_minus_shallow", "deep_reply"), ("root_minus_shallow", "root_reply")):
        subset = ratings[ratings["depth_bin"].isin(["shallow_reply", level])]
        balance[name] = _clustered_slope(
            subset["frame_acceptable"],
            subset["depth_bin"].eq(level),
            subset["item_id"],
            subset["assignment_id"],
        )
    summary["acceptability_balance"] = balance

    strata = []
    for column in ("depth_bin", "core", "ranking", "community", "polarity"):
        for level, group in ratings.groupby(column, dropna=False):
            strata.append(
                {
                    "stratum": column,
                    "level": str(level),
                    "ratings": int(len(group)),
                    "frame_acceptable": float(group["frame_acceptable"].mean()),
                    "verbatim_acceptable": float(group["verbatim_acceptable"].mean()),
                }
            )

    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "summary.json").write_text(
        json.dumps(summary, indent=2, sort_keys=True), encoding="utf-8"
    )
    pd.DataFrame(strata).to_csv(output_dir / "stratified_acceptability.csv", index=False)
    _write_tex(summary, output_dir)
    return summary


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    summary = analyze(args.input, args.output_dir)
    acceptable = summary["acceptable"]
    difference = summary["paired_differences"]["acceptable"]
    print(
        "acceptable: "
        f"frame={100 * acceptable['frame']['estimate']:.1f}%, "
        f"verbatim={100 * acceptable['verbatim']['estimate']:.1f}%, "
        f"difference={100 * difference['estimate']:+.1f} pp "
        f"[{100 * difference['ci_low']:+.1f}, {100 * difference['ci_high']:+.1f}]"
    )


if __name__ == "__main__":
    main()
