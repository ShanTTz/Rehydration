"""Analyze blinded semantic ratings with item and assignment clustering.

The primary acceptability rule treats a rendered reply as minimally executable
when both relevance and coherence are at least 3/5 and no obvious mismatch is
reported.  The stricter 4/5 rule is retained as a secondary stress test.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd
import statsmodels.api as sm
from statsmodels.stats.sandwich_covariance import cov_cluster_2groups


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = (
    ROOT
    / "artifacts"
    / "reviewer_validation"
    / "semantic_parent_audit"
    / "human_results_20260825"
    / "RATINGS_PAIRED_DECODED.csv"
)
DEFAULT_OUTPUT = DEFAULT_INPUT.parent / "two_way_cluster_analysis"


def _clustered_mean(values: pd.Series, item: pd.Series, assignment: pd.Series) -> dict[str, float]:
    y = values.astype(float).to_numpy()
    design = np.ones((len(y), 1), dtype=float)
    fit = sm.OLS(y, design).fit()
    item_codes = pd.factorize(item, sort=True)[0]
    assignment_codes = pd.factorize(assignment, sort=True)[0]
    covariance = cov_cluster_2groups(fit, item_codes, assignment_codes)[0]
    estimate = float(y.mean())
    standard_error = float(np.sqrt(covariance[0, 0]))
    return {
        "estimate": estimate,
        "standard_error": standard_error,
        "ci_low": estimate - 1.96 * standard_error,
        "ci_high": estimate + 1.96 * standard_error,
    }


def _clustered_slope(
    outcome: pd.Series,
    indicator: pd.Series,
    item: pd.Series,
    assignment: pd.Series,
) -> dict[str, float]:
    y = outcome.astype(float).to_numpy()
    design = sm.add_constant(indicator.astype(float).to_numpy())
    fit = sm.OLS(y, design).fit()
    item_codes = pd.factorize(item, sort=True)[0]
    assignment_codes = pd.factorize(assignment, sort=True)[0]
    covariance = cov_cluster_2groups(fit, item_codes, assignment_codes)[0]
    estimate = float(fit.params[1])
    standard_error = float(np.sqrt(covariance[1, 1]))
    return {
        "estimate": estimate,
        "standard_error": standard_error,
        "ci_low": estimate - 1.96 * standard_error,
        "ci_high": estimate + 1.96 * standard_error,
    }


def _add_validity_columns(ratings: pd.DataFrame) -> pd.DataFrame:
    ratings = ratings.copy()
    for source in ("frame", "verbatim"):
        ratings[f"{source}_acceptable"] = (
            (ratings[f"{source}_relevance"] >= 3)
            & (ratings[f"{source}_coherence"] >= 3)
            & (ratings[f"{source}_mismatch"] == 0)
        ).astype(int)
        ratings[f"{source}_strict"] = (
            (ratings[f"{source}_relevance"] >= 4)
            & (ratings[f"{source}_coherence"] >= 4)
            & (ratings[f"{source}_mismatch"] == 0)
        ).astype(int)
    return ratings


def _percent(value: float) -> float:
    return round(100.0 * value, 1)


